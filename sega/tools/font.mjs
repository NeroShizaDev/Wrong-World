// Кириллица, которая выглядит точно как латиница, берёт тот же рисунок.
export const ALIASES = {
  А: "A", В: "B", Е: "E", К: "K", М: "M", Н: "H", О: "O", Р: "P", С: "C", Т: "T", Х: "X",
  а: "a", е: "e", о: "o", р: "p", с: "c", у: "y", х: "x",
};

export function glyphRows(char) {
  const rows = GLYPHS[char] ?? GLYPHS[ALIASES[char]];
  if (!rows) return null;
  const width = Math.max(0, ...rows.map((row) => row.length));
  const offset = width > 6 ? 0 : 1;
  const out = [];
  for (let y = 0; y < 8; y += 1) {
    const row = rows[y] ?? "";
    let bits = "";
    for (let x = 0; x < 8; x += 1) bits += row[x - offset] === "#" ? "1" : "0";
    out.push(bits);
  }
  return out;
}
