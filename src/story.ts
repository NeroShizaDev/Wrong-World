export function checkCondition(condition: Condition | undefined, context: StoryContext): boolean {
  if (!condition) return true;
  const { mem, run, depth } = context;
  if (condition.mem && !condition.mem.every((key) => mem.has(key))) return false;
  if (condition.noMem && condition.noMem.some((key) => mem.has(key))) return false;
  if (condition.run && !condition.run.every((flag) => run.has(flag))) return false;
  if (condition.noRun && condition.noRun.some((flag) => run.has(flag))) return false;
  if (condition.minDepth !== undefined && depth < condition.minDepth) return false;
  if (condition.maxDepth !== undefined && depth > condition.maxDepth) return false;
  return true;
}

export function sceneVariants(scene: SceneDef): SceneVariant[] {
  return "variants" in scene ? scene.variants : [scene];
}

/** Первый подходящий вариант сцены; последний вариант служит запасным. */
export function resolveScene(scene: SceneDef, context: StoryContext): SceneVariant {
  const variants = sceneVariants(scene);
  return variants.find((variant) => checkCondition(variant.if, context)) ?? variants[variants.length - 1];
}

export function lastDeathLabel(lastDeath: DeathId | null | undefined): string {
  return lastDeath === null || lastDeath === undefined ? "что-то нелепое" : `«${DEATHS[lastDeath].name}»`;
}

export function sceneText(variant: SceneVariant, context: StoryContext): string {
  const notes = (variant.notes ?? []).filter((note) => checkCondition(note.if, context)).map((note) => note.text);
  return [variant.text, ...notes].join("\n").replaceAll(LAST_DEATH_TOKEN, lastDeathLabel(context.lastDeath));
}

/** Выбор, открытый памятью о прошлых смертях, показывается как озарение (⚡). */
export function isInsight(choice: ChoiceDef): boolean {
  return (choice.if?.mem?.length ?? 0) > 0;
}
