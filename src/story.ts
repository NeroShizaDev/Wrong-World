/** Условие показа сцены, варианта или выбора. Все перечисленные требования должны выполняться. */
export type Condition = {
  /** Что герой помнит между жизнями (номера смертей и флаги знаний). */
  mem?: MemoryKey[];
  noMem?: MemoryKey[];
  /** Что произошло в текущей жизни (сбрасывается при смерти). */
  run?: string[];
  noRun?: string[];
  /** Уровень вложенности «игры в игре»: 0 — настоящая комната. */
  minDepth?: number;
  maxDepth?: number;
};

export type ChoiceAction = "launch" | "exit" | "win";

export type ChoiceDef = {
  text: string;
  to?: string;
  action?: ChoiceAction;
  ending?: EndingId;
  if?: Condition;
};

export type SceneVariant = {
  if?: Condition;
  /** Можно вставить {lastDeath} — название прошлой смерти героя. */
  text: string;
  /** Дополнительные строки, которые дописываются к тексту, если условие выполнено. */
  notes?: { if: Condition; text: string }[];
  choices?: ChoiceDef[];
  death?: DeathId;
  set?: string[];
  unset?: string[];
  remember?: MemoryKey[];
  /** false — в этой сцене не предлагать «Стоять столбом». */
  idle?: boolean;
  /** Показать перед текстом описание графики текущего слоя (для игры в игре). */
  showGraphics?: boolean;
  /** Музыка сцены в настоящей комнате; без поля играет основная тема. */
  music?: SceneMusic;
};

export type SceneMusic = "computer";

export type SceneDef = SceneVariant | { variants: SceneVariant[] };

export type StoryContext = {
  mem: ReadonlySet<MemoryKey>;
  run: ReadonlySet<string>;
  depth: number;
  lastDeath?: DeathId | null;
};

